/**
 * Public legal documents. The provider's requisites come from the platform settings,
 * prices from the current public tariffs, so the documents never drift from what the service charges.
 */
const reqLine = (s) => [s.reqName, s.reqInn && `ИНН ${s.reqInn}`, s.reqKpp && `КПП ${s.reqKpp}`, s.reqOgrn && `ОГРН ${s.reqOgrn}`].filter(Boolean).join(', ');
const contacts = (s) => [s.supportEmail && `эл. почта <a href="mailto:${esc(s.supportEmail)}">${esc(s.supportEmail)}</a>`, s.supportPhone && `телефон ${esc(s.supportPhone)}`].filter(Boolean).join(', ') || 'через раздел поддержки в личном кабинете';
const who = (s) => esc(s.reqName || 'Исполнитель');

function requisites(s) {
  const ready = s.reqName && s.reqInn;
  return `<section id="req"><h2>Реквизиты</h2>
    ${ready ? '' : '<p class="flash flash-warn">Реквизиты ещё не заполнены. Администратор платформы указывает их в «Настройках».</p>'}
    <dl class="legal-req">
      <dt>Наименование</dt><dd>${esc(s.reqName || '—')}</dd>
      <dt>ИНН / КПП</dt><dd>${esc(s.reqInn || '—')}${s.reqKpp ? ' / ' + esc(s.reqKpp) : ''}</dd>
      ${s.reqOgrn ? `<dt>ОГРН</dt><dd>${esc(s.reqOgrn)}</dd>` : ''}
      <dt>Адрес</dt><dd>${esc(s.reqAddr || '—')}</dd>
      ${s.reqAccount ? `<dt>Расчётный счёт</dt><dd class="mono">${esc(s.reqAccount)}</dd><dt>Банк</dt><dd>${esc(s.reqBank || '')}, БИК ${esc(s.reqBic || '')}, к/с ${esc(s.reqCorr || '')}</dd>` : ''}
      <dt>Связь</dt><dd>${contacts(s)}</dd>
    </dl></section>`;
}

const head = (title, s) => `<header class="legal-head"><h1>${title}</h1>
  <p class="muted">${s.legalDate ? `Редакция от ${ruDay(s.legalDate)}. ` : ''}${s.reqName ? esc(reqLine(s)) : ''}</p></header>`;

